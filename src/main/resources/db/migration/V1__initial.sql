CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('CANDIDATE', 'RECRUITER'))
);
CREATE TABLE slots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recruiter_id BIGINT NOT NULL REFERENCES accounts(id),
 candidate_id BIGINT REFERENCES accounts(id),
 starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
 ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT valid_interval CHECK (ends_at > starts_at)
);
CREATE INDEX slots_start_idx ON slots(starts_at);
